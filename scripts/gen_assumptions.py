"""Render ASSUMPTIONS.md from engine.factors.table(). Plan step 07.5.b.

Run with ``make assumptions`` (or ``python scripts/gen_assumptions.py``). The rows come from the
same ``handlers.assumptions.build`` that serves ``GET /assumptions``, so this file and the website
can never disagree. ``--check`` exits 1 when the committed file is stale (for CI).
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from engine.factors import load_factors  # noqa: E402
from handlers.assumptions import build  # noqa: E402

OUT = ROOT / "ASSUMPTIONS.md"
STATUS_ORDER = ("measured", "sourced", "calibrated", "design_choice", "placeholder", "unverified")


def _num(value: Any) -> str:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return str(value)
    return f"{value:g}"


def _cell(text: Any) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def _range(row: dict[str, Any]) -> str:
    low, value, high = row.get("low"), row.get("value"), row.get("high")
    if low == value == high:
        return _num(value)
    return f"{_num(value)} ({_num(low)} to {_num(high)})"


def _source(row: dict[str, Any]) -> str:
    text, url = _cell(row.get("source")), str(row.get("source_url") or "")
    return f"[{text or url}]({url})" if url else text


def render(body: dict[str, Any]) -> str:
    rows: list[dict[str, Any]] = body["factors"]
    counts = Counter(str(r["status"]) for r in rows)
    order = [s for s in STATUS_ORDER if s in counts] + sorted(set(counts) - set(STATUS_ORDER))
    mix = " · ".join(f"{counts[s]} {s.replace('_', ' ')}" for s in order)
    out = [
        "# Assumptions",
        "",
        "<!-- Generated by scripts/gen_assumptions.py (make assumptions). Do not edit by hand. -->",
        "",
        "Every number Thirst shows comes from this table, the same data as the website's",
        "[Assumptions page](https://main.dzxkrtlc7xqfx.amplifyapp.com/assumptions).",
        "Values are central (low to high); the low and high sets give the savings ranges.",
        "",
        f"- Factor data version: `{body['version']}`",
        f"- {len(rows)} factors: {mix}",
        "",
        "| Status | Meaning |",
        "|---|---|",
        "| measured | read from hardware (NVML) or our own power-cap sweep |",
        "| sourced | taken from a published source we cite |",
        "| calibrated | adjusted so the model matches a published yearly figure |",
        "| design choice | our choice, written down so anyone can change it |",
        "| placeholder | a stand-in until we measure or source the real value |",
        "",
    ]
    groups: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        groups.setdefault(str(row["group"]), []).append(row)
    for group, items in groups.items():
        out += [
            f"## {group.replace('_', ' ').capitalize()}",
            "",
            "| Id | What | Value (low to high) | Unit | Status | Source | Notes |",
            "|---|---|---|---|---|---|---|",
        ]
        out += [
            f"| `{r['id']}` | {_cell(r['label'])} | {_range(r)} | {_cell(r['unit'])}"
            f" | {r['status']} | {_source(r)} | {_cell(r.get('notes'))} |"
            for r in items
        ]
        out.append("")
    out += [
        "## Cities",
        "",
        "| City | Water-stress category | Stress weight | Status |",
        "|---|---|---|---|",
    ]
    out += [
        f"| {c['id']} | {c['stress_category'].replace('_', ' ')} | {_num(c['stress_weight'])}"
        f" | {c['status']} |"
        for c in body["cities"]
    ]
    out += [
        "",
        "## GPUs",
        "",
        "| GPU | Max power (W) | Idle power (W) | Power-cap sweep |",
        "|---|---|---|---|",
    ]
    out += [
        f"| {g['label']} (`{g['id']}`) | {_num(g['p_max_w'])} | {_num(g['p_idle_w'])}"
        f" | {g['sweep_status']} |"
        for g in body["gpus"]
    ]
    out += ["", "## Sources and licences", "", "| Source | Used for | Licence |", "|---|---|---|"]
    out += [
        f"| [{s['name']}]({s['url']}) | {s['used_for']} | {s['licence']} |" for s in body["sources"]
    ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if ASSUMPTIONS.md is stale")
    args = parser.parse_args(argv)
    text = render(build(load_factors()))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("ASSUMPTIONS.md is stale: run `make assumptions`.")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
